import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseDocument } from "yaml";

const EVE_FORMAT = "vercel.com/eve:v1";
const EVE_VERSION = "0.27.8";
const AI_SDK_VERSION = "7.0.34";
const NODE_TYPES_VERSION = "24.1.0";
const TYPESCRIPT_VERSION = "5.9.2";

function parseImplementationPackage(source, packagePath, resourceId) {
  const document = parseDocument(source, {
    prettyErrors: true,
    uniqueKeys: true,
  });

  if (document.errors.length > 0) {
    throw new Error(
      `resource '${resourceId}' package ${packagePath} is invalid YAML: ${document.errors
        .map((error) => error.message)
        .join("; ")}`,
    );
  }

  const payload = document.toJS();
  if (
    payload === null ||
    typeof payload !== "object" ||
    Array.isArray(payload)
  ) {
    throw new Error(
      `resource '${resourceId}' package ${packagePath} must contain a YAML mapping`,
    );
  }

  const supportedFields = new Set(["instructions", "model"]);
  const unsupportedFields = Object.keys(payload).filter(
    (field) => !supportedFields.has(field),
  );
  if (unsupportedFields.length > 0) {
    throw new Error(
      `resource '${resourceId}': Eve v1 implementation package does not support field${unsupportedFields.length === 1 ? "" : "s"} ${unsupportedFields.map((field) => `'${field}'`).join(", ")}`,
    );
  }

  if (
    typeof payload.model !== "string" ||
    !/^\S+\/\S+$/.test(payload.model)
  ) {
    throw new Error(
      `resource '${resourceId}': Eve v1 implementation package field 'model' must be a provider/model identifier`,
    );
  }
  if (
    typeof payload.instructions !== "string" ||
    payload.instructions.trim().length === 0
  ) {
    throw new Error(
      `resource '${resourceId}': Eve v1 implementation package field 'instructions' must be a non-empty string`,
    );
  }

  return {
    instructions: `${payload.instructions.trimEnd()}\n`,
    model: payload.model,
  };
}

function environmentVariableName(secretId) {
  return secretId.replaceAll("-", "_").toUpperCase();
}

function connectionSource(resource) {
  const fields = [
    `  url: ${JSON.stringify(resource.connection.url)},`,
    `  description: ${JSON.stringify(
      `MCP server '${resource.id}' at ${new URL(resource.connection.url).hostname}.`,
    )},`,
  ];

  if (resource.authentication) {
    const secretId = resource.authentication.secret.ref;
    const variable = environmentVariableName(secretId);
    fields.push(
      "  auth: {",
      "    async getToken() {",
      `      const token = process.env.${variable};`,
      "      if (!token) {",
      `        throw new Error(${JSON.stringify(
        `Missing required environment variable ${variable} for secret requirement '${secretId}'`,
      )});`,
      "      }",
      "      return { token };",
      "    },",
      "  },",
    );
  }

  return [
    'import { defineMcpClientConnection } from "eve/connections";',
    "",
    "export default defineMcpClientConnection({",
    ...fields,
    "});",
    "",
  ].join("\n");
}

function generatedPackageJson(manifest) {
  return {
    name: manifest.metadata.name,
    version: manifest.metadata.version,
    private: true,
    type: "module",
    engines: {
      node: ">=24",
    },
    scripts: {
      build: "eve build",
      deploy: "eve deploy",
      dev: "eve dev",
      start: "eve start",
    },
    dependencies: {
      ai: AI_SDK_VERSION,
      eve: EVE_VERSION,
    },
    devDependencies: {
      "@types/node": NODE_TYPES_VERSION,
      typescript: TYPESCRIPT_VERSION,
    },
  };
}

function generatedReadme(manifest, secretBindings) {
  const secretSetup =
    secretBindings.length === 0
      ? "This app has no secret bindings."
      : [
          "Configure these environment variables in the Vercel project before deployment:",
          "",
          ...secretBindings.map(
            ({ requirementId, environmentVariable }) =>
              `- \`${environmentVariable}\` for \`${requirementId}\``,
          ),
        ].join("\n");

  return `# ${manifest.metadata.name}

Generated by \`aiappctl build --runtime eve\` from AI App Spec package version ${manifest.metadata.version}.

This directory is generated output. Rebuild it from the source app package instead of editing it in place.

## Run locally

Node.js 24 or later is required.

\`\`\`sh
npm install
npm run dev
\`\`\`

${secretSetup}

Local values may be placed in \`.env.local\`. Do not commit that file.

## Deploy to Vercel

\`\`\`sh
npm install
npx eve link
npm run build
npm run deploy
\`\`\`
`;
}

function generatedBuildManifest(
  manifest,
  resource,
  secretBindings,
  executionEnvironment,
) {
  return {
    schemaVersion: 1,
    source: {
      apiVersion: manifest.apiVersion,
      app: manifest.metadata.name,
      version: manifest.metadata.version,
      entrypoint: manifest.spec.entrypoint,
      implementation: {
        format: resource.implementation.format,
        digest: resource.implementation.package.digest,
      },
    },
    runtime: {
      name: "eve",
      package: "eve",
      version: EVE_VERSION,
    },
    bindings: {
      secrets: secretBindings,
      executionEnvironment: executionEnvironment
        ? {
            requirementId: executionEnvironment.id,
            networking: {
              mcpServers:
                executionEnvironment.networking?.mcpServers ?? false,
            },
          }
        : null,
    },
  };
}

async function outputExists(outPath) {
  try {
    await stat(outPath);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") {
      return false;
    }
    throw error;
  }
}

async function writeProject(outPath, files) {
  if (await outputExists(outPath)) {
    throw new Error(
      `output path already exists: ${outPath}; choose a new --out directory`,
    );
  }

  await mkdir(outPath, { recursive: true });
  for (const [relativePath, contents] of files) {
    const destination = path.join(outPath, relativePath);
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, contents, {
      encoding: "utf8",
      flag: "wx",
    });
  }
}

async function compile(validation) {
  const { manifest } = validation;
  const agents = manifest.spec.resources.filter(
    (resource) => resource.kind === "Agent",
  );
  if (agents.length !== 1) {
    throw new Error(
      `Eve v1 build requires exactly one Agent resource; found ${agents.length}`,
    );
  }

  const resource = agents[0];
  if (manifest.spec.entrypoint !== resource.id) {
    throw new Error(
      `Eve v1 build requires Agent '${resource.id}' to be the app entrypoint`,
    );
  }
  if (!resource.implementation.package.location.startsWith("./")) {
    throw new Error(
      `resource '${resource.id}': Eve v1 build only supports package-relative implementation locations`,
    );
  }

  const packagePath = validation.resolvedPackages.get(resource.id);
  if (!packagePath) {
    throw new Error(
      `resource '${resource.id}': implementation package is unavailable`,
    );
  }

  const packagePayload = parseImplementationPackage(
    await readFile(packagePath, "utf8"),
    packagePath,
    resource.id,
  );
  const resourcesById = new Map(
    manifest.spec.resources.map((candidate) => [candidate.id, candidate]),
  );
  const referencedToolIds = new Set(
    (resource.tools || []).map((reference) => reference.ref),
  );
  const mcpServers = manifest.spec.resources.filter(
    (candidate) => candidate.kind === "MCPServer",
  );
  const unreferencedServers = mcpServers.filter(
    (server) => !referencedToolIds.has(server.id),
  );
  if (unreferencedServers.length > 0) {
    throw new Error(
      `Eve v1 build cannot represent unreferenced MCPServer resource${unreferencedServers.length === 1 ? "" : "s"} ${unreferencedServers.map((server) => `'${server.id}'`).join(", ")}`,
    );
  }

  for (const toolId of referencedToolIds) {
    const server = resourcesById.get(toolId);
    if (!server || server.kind !== "MCPServer") {
      throw new Error(
        `resource '${resource.id}': referenced tool resource '${toolId}' is not an MCPServer`,
      );
    }
  }

  const executionEnvironment = resource.executionEnvironment
    ? (
        manifest.spec.requirements?.executionEnvironments || []
      ).find(
        (requirement) =>
          requirement.id === resource.executionEnvironment.ref,
      )
    : undefined;
  if (resource.executionEnvironment && !executionEnvironment) {
    throw new Error(
      `resource '${resource.id}': execution environment requirement '${resource.executionEnvironment.ref}' does not exist`,
    );
  }
  if (
    mcpServers.length > 0 &&
    executionEnvironment &&
    !executionEnvironment.networking?.mcpServers
  ) {
    throw new Error(
      `resource '${resource.id}': Eve MCP connections require execution environment '${executionEnvironment.id}' to enable networking.mcpServers`,
    );
  }

  const secretBindingsByRequirement = new Map();
  for (const server of mcpServers) {
    if (server.authentication) {
      const requirementId = server.authentication.secret.ref;
      secretBindingsByRequirement.set(requirementId, {
        requirementId,
        environmentVariable: environmentVariableName(requirementId),
      });
    }
  }
  const secretBindings = [...secretBindingsByRequirement.values()];
  const consumedSecrets = new Set(
    secretBindings.map((binding) => binding.requirementId),
  );
  const unusedSecrets = (
    manifest.spec.requirements?.secrets || []
  ).filter((requirement) => !consumedSecrets.has(requirement.id));
  if (unusedSecrets.length > 0) {
    throw new Error(
      `Eve v1 build cannot represent unused secret requirement${unusedSecrets.length === 1 ? "" : "s"} ${unusedSecrets.map((requirement) => `'${requirement.id}'`).join(", ")}`,
    );
  }

  const files = new Map([
    [
      ".env.example",
      `${secretBindings
        .map(({ environmentVariable }) => `${environmentVariable}=`)
        .join("\n")}${secretBindings.length > 0 ? "\n" : ""}`,
    ],
    [
      ".gitignore",
      [
        ".env",
        ".env.*",
        "!.env.example",
        ".eve/",
        ".output/",
        ".vercel/",
        "node_modules/",
        "",
      ].join("\n"),
    ],
    [
      "README.md",
      generatedReadme(manifest, secretBindings),
    ],
    [
      "aiappctl.build.json",
      `${JSON.stringify(
        generatedBuildManifest(
          manifest,
          resource,
          secretBindings,
          executionEnvironment,
        ),
        null,
        2,
      )}\n`,
    ],
    [
      "agent/agent.ts",
      [
        'import { defineAgent } from "eve";',
        "",
        "export default defineAgent({",
        `  model: ${JSON.stringify(packagePayload.model)},`,
        "});",
        "",
      ].join("\n"),
    ],
    ["agent/instructions.md", packagePayload.instructions],
    [
      "package.json",
      `${JSON.stringify(generatedPackageJson(manifest), null, 2)}\n`,
    ],
    [
      "tsconfig.json",
      `${JSON.stringify(
        {
          compilerOptions: {
            target: "ES2022",
            module: "NodeNext",
            moduleResolution: "NodeNext",
            strict: true,
            skipLibCheck: true,
            types: ["node"],
          },
          include: ["agent/**/*.ts"],
        },
        null,
        2,
      )}\n`,
    ],
  ]);

  for (const server of mcpServers) {
    files.set(
      `agent/connections/${server.id}.ts`,
      connectionSource(server),
    );
  }

  return { files };
}

export const eveRuntime = {
  name: "eve",
  formats: new Set([EVE_FORMAT]),

  async build(validation, options) {
    try {
      const compiled = await compile(validation);
      const outPath = path.resolve(options.outPath);
      await writeProject(outPath, compiled.files);

      return {
        manifestPath: validation.manifestPath,
        manifest: validation.manifest,
        outPath,
        runtime: this.name,
        generatedFiles: [...compiled.files.keys()],
        errors: [],
      };
    } catch (error) {
      return {
        manifestPath: validation.manifestPath,
        errors: [error.message],
      };
    }
  },
};
