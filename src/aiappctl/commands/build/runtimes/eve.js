import { createHash, randomUUID } from "node:crypto";
import {
  mkdir,
  readFile,
  rename,
  stat,
  unlink,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { parseDocument } from "yaml";

const EVE_FORMAT = "vercel.com/eve:v1";
const BUILD_MANIFEST_FILENAME = "aiappctl.build.json";
const BUILD_MANIFEST_SCHEMA_VERSION = 2;
const AIAPPCTL_VERSION = "0.1.0";
const EVE_VERSION = "0.27.8";
const AI_SDK_VERSION = "7.0.34";
const NODE_TYPES_VERSION = "24.1.0";
const TYPESCRIPT_VERSION = "5.9.2";

function parseImplementationPackage(source, packagePath, resourceId) {
  const document = parseDocument(source, {
    prettyErrors: true,
    uniqueKeys: true,
  });

  if (document.errors.length > 0) {
    throw new Error(
      `resource '${resourceId}' package ${packagePath} is invalid YAML: ${document.errors
        .map((error) => error.message)
        .join("; ")}`,
    );
  }

  const payload = document.toJS();
  if (
    payload === null ||
    typeof payload !== "object" ||
    Array.isArray(payload)
  ) {
    throw new Error(
      `resource '${resourceId}' package ${packagePath} must contain a YAML mapping`,
    );
  }

  const supportedFields = new Set(["instructions", "model"]);
  const unsupportedFields = Object.keys(payload).filter(
    (field) => !supportedFields.has(field),
  );
  if (unsupportedFields.length > 0) {
    throw new Error(
      `resource '${resourceId}': Eve v1 implementation package does not support field${unsupportedFields.length === 1 ? "" : "s"} ${unsupportedFields.map((field) => `'${field}'`).join(", ")}`,
    );
  }

  if (
    typeof payload.model !== "string" ||
    !/^\S+\/\S+$/.test(payload.model)
  ) {
    throw new Error(
      `resource '${resourceId}': Eve v1 implementation package field 'model' must be a provider/model identifier`,
    );
  }
  if (
    typeof payload.instructions !== "string" ||
    payload.instructions.trim().length === 0
  ) {
    throw new Error(
      `resource '${resourceId}': Eve v1 implementation package field 'instructions' must be a non-empty string`,
    );
  }

  return {
    instructions: `${payload.instructions.trimEnd()}\n`,
    model: payload.model,
  };
}

function environmentVariableName(secretId) {
  return secretId.replaceAll("-", "_").toUpperCase();
}

function connectionSource(resource) {
  const fields = [
    `  url: ${JSON.stringify(resource.connection.url)},`,
    `  description: ${JSON.stringify(
      `MCP server '${resource.id}' at ${new URL(resource.connection.url).hostname}.`,
    )},`,
  ];

  if (resource.authentication) {
    const secretId = resource.authentication.secret.ref;
    const variable = environmentVariableName(secretId);
    fields.push(
      "  auth: {",
      "    async getToken() {",
      `      const token = process.env.${variable};`,
      "      if (!token) {",
      `        throw new Error(${JSON.stringify(
        `Missing required environment variable ${variable} for secret requirement '${secretId}'`,
      )});`,
      "      }",
      "      return { token };",
      "    },",
      "  },",
    );
  }

  return [
    'import { defineMcpClientConnection } from "eve/connections";',
    "",
    "export default defineMcpClientConnection({",
    ...fields,
    "});",
    "",
  ].join("\n");
}

function generatedPackageJson(manifest) {
  return {
    name: manifest.metadata.name,
    version: manifest.metadata.version,
    private: true,
    type: "module",
    engines: {
      node: ">=24",
    },
    scripts: {
      build: "eve build",
      deploy: "eve deploy",
      dev: "eve dev",
      start: "eve start",
    },
    dependencies: {
      ai: AI_SDK_VERSION,
      eve: EVE_VERSION,
    },
    devDependencies: {
      "@types/node": NODE_TYPES_VERSION,
      typescript: TYPESCRIPT_VERSION,
    },
  };
}

function generatedReadme(manifest, secretBindings) {
  const secretSetup =
    secretBindings.length === 0
      ? "This app has no secret bindings."
      : [
          "Configure these environment variables in the Vercel project before deployment:",
          "",
          ...secretBindings.map(
            ({ requirementId, environmentVariable }) =>
              `- \`${environmentVariable}\` for \`${requirementId}\``,
          ),
        ].join("\n");

  return `# ${manifest.metadata.name}

Generated by \`aiappctl build --runtime eve\` from AI App Spec package version ${manifest.metadata.version}.

This directory is generated output. Rebuild it from the source app package instead of editing it in place.

## Run locally

Node.js 24 or later is required.

\`\`\`sh
bun install
bun run dev
\`\`\`

${secretSetup}

Local values may be placed in \`.env.local\`. Do not commit that file.

## Deploy to Vercel

\`\`\`sh
bun install
bunx eve link
bun run build
bun run deploy
\`\`\`
`;
}

function generatedBuildManifest(
  manifest,
  resource,
  secretBindings,
  executionEnvironment,
  generatedFiles,
) {
  return {
    schemaVersion: BUILD_MANIFEST_SCHEMA_VERSION,
    generator: {
      name: "aiappctl",
      version: AIAPPCTL_VERSION,
    },
    source: {
      apiVersion: manifest.apiVersion,
      app: manifest.metadata.name,
      version: manifest.metadata.version,
      entrypoint: manifest.spec.entrypoint,
      implementation: {
        format: resource.implementation.format,
        digest: resource.implementation.package.digest,
      },
    },
    runtime: {
      name: "eve",
      package: "eve",
      version: EVE_VERSION,
    },
    bindings: {
      secrets: secretBindings,
      executionEnvironment: executionEnvironment
        ? {
            requirementId: executionEnvironment.id,
            networking: {
              mcpServers:
                executionEnvironment.networking?.mcpServers ?? false,
            },
          }
        : null,
    },
    generatedFiles,
  };
}

function sha256(contents) {
  return `sha256:${createHash("sha256").update(contents).digest("hex")}`;
}

function generatedFileDigests(files) {
  return Object.fromEntries(
    [...files.entries()]
      .sort(([left], [right]) =>
        left < right ? -1 : left > right ? 1 : 0,
      )
      .map(([relativePath, contents]) => [
        relativePath,
        sha256(contents),
      ]),
  );
}

async function outputExists(outPath) {
  try {
    await stat(outPath);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") {
      return false;
    }
    throw error;
  }
}

function managedDestination(outPath, relativePath) {
  if (
    typeof relativePath !== "string" ||
    relativePath.length === 0 ||
    relativePath === "." ||
    relativePath === ".." ||
    relativePath.startsWith("../") ||
    relativePath.includes("\\") ||
    path.posix.isAbsolute(relativePath) ||
    path.posix.normalize(relativePath) !== relativePath ||
    relativePath === BUILD_MANIFEST_FILENAME
  ) {
    throw new Error(
      `invalid managed file path '${relativePath}' in ${BUILD_MANIFEST_FILENAME}`,
    );
  }

  return path.join(outPath, ...relativePath.split("/"));
}

async function atomicWrite(destination, contents) {
  await mkdir(path.dirname(destination), { recursive: true });
  const temporaryPath = path.join(
    path.dirname(destination),
    `.${path.basename(destination)}.aiappctl-${randomUUID()}.tmp`,
  );

  try {
    await writeFile(temporaryPath, contents, {
      encoding: "utf8",
      flag: "wx",
    });
    await rename(temporaryPath, destination);
  } finally {
    try {
      await unlink(temporaryPath);
    } catch (error) {
      if (error.code !== "ENOENT") {
        throw error;
      }
    }
  }
}

function parsePreviousBuildManifest(source, outPath) {
  let manifest;
  try {
    manifest = JSON.parse(source);
  } catch {
    throw new Error(
      `existing ${BUILD_MANIFEST_FILENAME} is not valid JSON: ${outPath}`,
    );
  }

  if (manifest?.schemaVersion !== BUILD_MANIFEST_SCHEMA_VERSION) {
    throw new Error(
      `existing ${BUILD_MANIFEST_FILENAME} uses unsupported schema version '${manifest?.schemaVersion ?? "missing"}'; rebuild into a new --out directory`,
    );
  }
  if (manifest.runtime?.name !== "eve") {
    throw new Error(
      `existing ${BUILD_MANIFEST_FILENAME} is not an Eve build: ${outPath}`,
    );
  }
  if (
    manifest.generatedFiles === null ||
    typeof manifest.generatedFiles !== "object" ||
    Array.isArray(manifest.generatedFiles)
  ) {
    throw new Error(
      `existing ${BUILD_MANIFEST_FILENAME} does not contain generated file digests: ${outPath}`,
    );
  }

  for (const [relativePath, digest] of Object.entries(
    manifest.generatedFiles,
  )) {
    managedDestination(outPath, relativePath);
    if (!/^sha256:[a-f0-9]{64}$/.test(digest)) {
      throw new Error(
        `invalid digest for managed file '${relativePath}' in ${BUILD_MANIFEST_FILENAME}`,
      );
    }
  }

  return manifest;
}

async function readPreviousBuildManifest(outPath) {
  const manifestPath = path.join(outPath, BUILD_MANIFEST_FILENAME);
  let source;
  try {
    source = await readFile(manifestPath, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") {
      throw new Error(
        `output path exists without ${BUILD_MANIFEST_FILENAME}: ${outPath}`,
      );
    }
    throw error;
  }
  return parsePreviousBuildManifest(source, outPath);
}

async function verifyManagedFiles(outPath, generatedFiles) {
  const driftedFiles = [];

  for (const [relativePath, expectedDigest] of Object.entries(
    generatedFiles,
  )) {
    const destination = managedDestination(outPath, relativePath);
    let contents;
    try {
      contents = await readFile(destination);
    } catch (error) {
      if (error.code === "ENOENT") {
        driftedFiles.push(relativePath);
        continue;
      }
      throw error;
    }

    if (sha256(contents) !== expectedDigest) {
      driftedFiles.push(relativePath);
    }
  }

  if (driftedFiles.length > 0) {
    throw new Error(
      `generated Eve project has drifted in managed file${driftedFiles.length === 1 ? "" : "s"}: ${driftedFiles.map((relativePath) => `'${relativePath}'`).join(", ")}`,
    );
  }
}

async function assertNewManagedPathsAvailable(
  outPath,
  previousFiles,
  nextFiles,
) {
  const conflicts = [];
  for (const relativePath of nextFiles.keys()) {
    if (
      !Object.hasOwn(previousFiles, relativePath) &&
      (await outputExists(managedDestination(outPath, relativePath)))
    ) {
      conflicts.push(relativePath);
    }
  }

  if (conflicts.length > 0) {
    throw new Error(
      `cannot create generated file${conflicts.length === 1 ? "" : "s"} over unmanaged path${conflicts.length === 1 ? "" : "s"}: ${conflicts.map((relativePath) => `'${relativePath}'`).join(", ")}`,
    );
  }
}

async function createProject(outPath, compiled) {
  await mkdir(outPath, { recursive: true });
  for (const [relativePath, contents] of compiled.files) {
    await atomicWrite(
      managedDestination(outPath, relativePath),
      contents,
    );
  }
  await atomicWrite(
    path.join(outPath, BUILD_MANIFEST_FILENAME),
    compiled.buildManifestSource,
  );
}

async function reconcileProject(outPath, compiled) {
  const outStat = await stat(outPath);
  if (!outStat.isDirectory()) {
    throw new Error(`output path is not a directory: ${outPath}`);
  }

  const previousManifest = await readPreviousBuildManifest(outPath);
  if (previousManifest.source?.app !== compiled.buildManifest.source.app) {
    throw new Error(
      `output path belongs to App '${previousManifest.source?.app ?? "unknown"}', not '${compiled.buildManifest.source.app}'`,
    );
  }

  await verifyManagedFiles(outPath, previousManifest.generatedFiles);
  await assertNewManagedPathsAvailable(
    outPath,
    previousManifest.generatedFiles,
    compiled.files,
  );

  for (const [relativePath, contents] of compiled.files) {
    const nextDigest = compiled.buildManifest.generatedFiles[relativePath];
    if (previousManifest.generatedFiles[relativePath] === nextDigest) {
      continue;
    }
    await atomicWrite(
      managedDestination(outPath, relativePath),
      contents,
    );
  }

  for (const relativePath of Object.keys(
    previousManifest.generatedFiles,
  )) {
    if (!compiled.files.has(relativePath)) {
      await unlink(managedDestination(outPath, relativePath));
    }
  }

  await atomicWrite(
    path.join(outPath, BUILD_MANIFEST_FILENAME),
    compiled.buildManifestSource,
  );
}

async function writeProject(outPath, compiled) {
  if (!(await outputExists(outPath))) {
    await createProject(outPath, compiled);
    return;
  }

  await reconcileProject(outPath, compiled);
}

async function compile(validation) {
  const { manifest } = validation;
  const agents = manifest.spec.resources.filter(
    (resource) => resource.kind === "Agent",
  );
  if (agents.length !== 1) {
    throw new Error(
      `Eve v1 build requires exactly one Agent resource; found ${agents.length}`,
    );
  }

  const resource = agents[0];
  if (manifest.spec.entrypoint !== resource.id) {
    throw new Error(
      `Eve v1 build requires Agent '${resource.id}' to be the app entrypoint`,
    );
  }
  if (!resource.implementation.package.location.startsWith("./")) {
    throw new Error(
      `resource '${resource.id}': Eve v1 build only supports package-relative implementation locations`,
    );
  }

  const packagePath = validation.resolvedPackages.get(resource.id);
  if (!packagePath) {
    throw new Error(
      `resource '${resource.id}': implementation package is unavailable`,
    );
  }

  const packagePayload = parseImplementationPackage(
    await readFile(packagePath, "utf8"),
    packagePath,
    resource.id,
  );
  const resourcesById = new Map(
    manifest.spec.resources.map((candidate) => [candidate.id, candidate]),
  );
  const referencedToolIds = new Set(
    (resource.tools || []).map((reference) => reference.ref),
  );
  const mcpServers = manifest.spec.resources.filter(
    (candidate) => candidate.kind === "MCPServer",
  );
  const unreferencedServers = mcpServers.filter(
    (server) => !referencedToolIds.has(server.id),
  );
  if (unreferencedServers.length > 0) {
    throw new Error(
      `Eve v1 build cannot represent unreferenced MCPServer resource${unreferencedServers.length === 1 ? "" : "s"} ${unreferencedServers.map((server) => `'${server.id}'`).join(", ")}`,
    );
  }

  for (const toolId of referencedToolIds) {
    const server = resourcesById.get(toolId);
    if (!server || server.kind !== "MCPServer") {
      throw new Error(
        `resource '${resource.id}': referenced tool resource '${toolId}' is not an MCPServer`,
      );
    }
  }

  const executionEnvironment = resource.executionEnvironment
    ? (
        manifest.spec.requirements?.executionEnvironments || []
      ).find(
        (requirement) =>
          requirement.id === resource.executionEnvironment.ref,
      )
    : undefined;
  if (resource.executionEnvironment && !executionEnvironment) {
    throw new Error(
      `resource '${resource.id}': execution environment requirement '${resource.executionEnvironment.ref}' does not exist`,
    );
  }
  if (
    mcpServers.length > 0 &&
    executionEnvironment &&
    !executionEnvironment.networking?.mcpServers
  ) {
    throw new Error(
      `resource '${resource.id}': Eve MCP connections require execution environment '${executionEnvironment.id}' to enable networking.mcpServers`,
    );
  }

  const secretBindingsByRequirement = new Map();
  for (const server of mcpServers) {
    if (server.authentication) {
      const requirementId = server.authentication.secret.ref;
      secretBindingsByRequirement.set(requirementId, {
        requirementId,
        environmentVariable: environmentVariableName(requirementId),
      });
    }
  }
  const secretBindings = [...secretBindingsByRequirement.values()];
  const consumedSecrets = new Set(
    secretBindings.map((binding) => binding.requirementId),
  );
  const unusedSecrets = (
    manifest.spec.requirements?.secrets || []
  ).filter((requirement) => !consumedSecrets.has(requirement.id));
  if (unusedSecrets.length > 0) {
    throw new Error(
      `Eve v1 build cannot represent unused secret requirement${unusedSecrets.length === 1 ? "" : "s"} ${unusedSecrets.map((requirement) => `'${requirement.id}'`).join(", ")}`,
    );
  }

  const files = new Map([
    [
      ".env.example",
      `${secretBindings
        .map(({ environmentVariable }) => `${environmentVariable}=`)
        .join("\n")}${secretBindings.length > 0 ? "\n" : ""}`,
    ],
    [
      ".gitignore",
      [
        ".env",
        ".env.*",
        "!.env.example",
        ".eve/",
        ".output/",
        ".vercel/",
        "node_modules/",
        "",
      ].join("\n"),
    ],
    [
      "README.md",
      generatedReadme(manifest, secretBindings),
    ],
    [
      "agent/agent.ts",
      [
        'import { defineAgent } from "eve";',
        "",
        "export default defineAgent({",
        `  model: ${JSON.stringify(packagePayload.model)},`,
        "});",
        "",
      ].join("\n"),
    ],
    ["agent/instructions.md", packagePayload.instructions],
    [
      "package.json",
      `${JSON.stringify(generatedPackageJson(manifest), null, 2)}\n`,
    ],
    [
      "tsconfig.json",
      `${JSON.stringify(
        {
          compilerOptions: {
            target: "ES2022",
            module: "NodeNext",
            moduleResolution: "NodeNext",
            strict: true,
            skipLibCheck: true,
            types: ["node"],
          },
          include: ["agent/**/*.ts"],
        },
        null,
        2,
      )}\n`,
    ],
  ]);

  for (const server of mcpServers) {
    files.set(
      `agent/connections/${server.id}.ts`,
      connectionSource(server),
    );
  }

  const buildManifest = generatedBuildManifest(
    manifest,
    resource,
    secretBindings,
    executionEnvironment,
    generatedFileDigests(files),
  );

  return {
    files,
    buildManifest,
    buildManifestSource: `${JSON.stringify(buildManifest, null, 2)}\n`,
  };
}

export const eveRuntime = {
  name: "eve",
  formats: new Set([EVE_FORMAT]),

  async build(validation, options) {
    try {
      const compiled = await compile(validation);
      const outPath = path.resolve(options.outPath);
      await writeProject(outPath, compiled);

      return {
        manifestPath: validation.manifestPath,
        manifest: validation.manifest,
        outPath,
        runtime: this.name,
        generatedFiles: [
          ...compiled.files.keys(),
          BUILD_MANIFEST_FILENAME,
        ],
        errors: [],
      };
    } catch (error) {
      return {
        manifestPath: validation.manifestPath,
        errors: [error.message],
      };
    }
  },
};
